export function CategoryIcon({
  name,
  className = "w-4 h-4",
  size = 16,
}: {
  name: string;
  className?: string;
  size?: number;
}) {
  switch (name.toLowerCase()) {
    case "grid":
    case "all":
      return <GridIcon className={className} size={size} />;
    case "sparkles":
    case "agency":
      return <SparklesIcon className={className} size={size} />;
    case "user":
    case "portfolio":
      return <UserIcon className={className} size={size} />;
    case "scissors":
    case "barber":
      return <ScissorsIcon className={className} size={size} />;
    case "utensils":
    case "restaurant":
      return <UtensilsIcon className={className} size={size} />;
    case "shirt":
    case "fashion":
      return <ShirtIcon className={className} size={size} />;
    case "droplet":
    case "cosmetics":
      return <DropletIcon className={className} size={size} />;
    case "shield":
    case "dental":
      return <ShieldIcon className={className} size={size} />;
    case "heart-pulse":
    case "medical":
      return <HeartPulseIcon className={className} size={size} />;
    case "compass":
    case "travel":
      return <CompassIcon className={className} size={size} />;
    case "car":
    case "cars":
      return <CarIcon className={className} size={size} />;
    case "gauge":
    case "motorcycle":
      return <GaugeIcon className={className} size={size} />;
    default:
      return <LayersIcon className={className} size={size} />;
  }
}
